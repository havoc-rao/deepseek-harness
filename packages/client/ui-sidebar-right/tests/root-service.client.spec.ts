/** Root contribution selection and teardown without Session state. */
import { expect, it, vi } from 'vitest'
import { SidebarRightRootController } from '../src/client/root-service.ts'

it('requires registered keys and closes only the selected contribution', () => {
  const release = vi.fn()
  const root = new SidebarRightRootController(release)
  expect(() => { root.open('missing') }).toThrow('unregistered key')
  const a = root.register('a')
  const b = root.register('b')
  expect(() => root.register('a')).toThrow('duplicate key')
  const changed = vi.fn()
  const stop = root.active.subscribe(changed)
  root.open('a')
  root.open('a')
  expect(changed).toHaveBeenCalledOnce()
  root.open('b')
  root.close('a')
  a()
  a()
  expect(root.active.getSnapshot()).toBe('b')
  expect(release).not.toHaveBeenCalled()
  b()
  expect(root.active.getSnapshot()).toBeUndefined()
  expect(release).toHaveBeenCalledOnce()
  root.close('b')
  expect(release).toHaveBeenCalledOnce()
  const replacement = root.register('a')
  root.open('a')
  a()
  expect(root.active.getSnapshot()).toBe('a')
  replacement()
  expect(root.active.getSnapshot()).toBeUndefined()
  stop()
})
